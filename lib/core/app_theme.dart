import 'package:flutter/material.dart';

/// Design tokens and typography for the Capture Studio application.
class AppColors {
  // Primary Palette - Premium Slate & Electric Blue
  static const Color primary = Color(0xFF2563EB); // Modern Royal Blue
  static const Color primaryDark = Color(0xFF1D4ED8);
  static const Color primaryLight = Color(0xFF60A5FA);

  // Surfaces & Backgrounds - Premium White & Soft Slate
  static const Color background = Color(0xFFF8FAFC);
  static const Color surface = Color(0xFFFFFFFF);
  static const Color surfaceElevated = Color(0xFFFFFFFF);

  // Typography
  static const Color textPrimary = Color(0xFF0F172A); // Slate 900
  static const Color textSecondary = Color(0xFF475569); // Slate 600
  static const Color textMuted = Color(0xFF94A3B8); // Slate 400

  // Camera Card Palette
  static const Color cameraCardBg = Color(0xFFEFF6FF); // Soft Pale Blue
  static const Color cameraCardBorder = Color(0xFFBFDBFE); // Soft Blue Border
